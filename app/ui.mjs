export const spark = (values, color='#236759') => {
  const min=Math.min(...values)-2, diff=Math.max(...values)-min+2;
  const points=values.map((v,i)=>[i/(values.length-1)*124, 32-(v-min)/diff*28]);
  const line=points.map(([x,y])=>x+','+y).join(' ');
  return `<svg class="spark" viewBox="0 0 124 36" aria-hidden="true"><polygon points="0,36 ${line} 124,36" fill="${color}" opacity=".09"/><polyline points="${line}" stroke="${color}" fill="none" stroke-width="2" stroke-linejoin="round"/></svg>`;
};
