const makeRoad = ([a, b, speed, delay, name, toll = 0, limit = 26, risk = 0]) => {
  const shape=geometry[a+':'+b];
  const km=shape.slice(1).reduce((sum,point,index)=>sum+roadKilometres(shape[index],point),0);
  return {a,b,km,speed,delay,name,toll,limit,risk,shape};
};
